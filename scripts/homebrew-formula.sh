#!/bin/sh
# Prints the Homebrew formula for a release, from the checksums that
# build-release.sh wrote.
# Usage: scripts/homebrew-formula.sh v0.1.0 dist/checksums.txt > Formula/sheaf.rb
set -eu

version=${1:?usage: $0 VERSION CHECKSUMS}
sums=${2:?usage: $0 VERSION CHECKSUMS}
v=${version#v}
base="https://github.com/sensahin/sheaf/releases/download/$version"

sha() {
	s=$(awk -v f="sheaf_${v}_$1.tar.gz" '$2 == f { print $1 }' "$sums")
	[ -n "$s" ] || { echo "no checksum for $1 in $sums" >&2; exit 1; }
	echo "$s"
}

# Look every checksum up first: a failure inside the heredoc's command
# substitutions would not stop the script.
for t in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
	sha "$t" >/dev/null
done

cat <<RUBY
# Generated by scripts/homebrew-formula.sh for $version. Do not edit.
class Sheaf < Formula
  desc "Local-first coordination layer for AI coding agents"
  homepage "https://github.com/sensahin/sheaf"
  version "$v"
  license "Apache-2.0"
  head "https://github.com/sensahin/sheaf.git", branch: "main"

  on_macos do
    on_arm do
      url "$base/sheaf_${v}_darwin_arm64.tar.gz"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "$base/sheaf_${v}_darwin_amd64.tar.gz"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$base/sheaf_${v}_linux_arm64.tar.gz"
      sha256 "$(sha linux_arm64)"
    end
    on_intel do
      url "$base/sheaf_${v}_linux_amd64.tar.gz"
      sha256 "$(sha linux_amd64)"
    end
  end

  head do
    depends_on "go" => :build
  end

  def install
    if build.head?
      system "go", "build", "-trimpath", "-o", bin/"sheaf", "-ldflags", "-s -w -X main.version=#{version}", "./cmd/sheaf"
    else
      bin.install "sheaf"
    end
  end

  service do
    run [opt_bin/"sheaf", "daemon"]
    keep_alive true
    log_path var/"log/sheaf.log"
    error_log_path var/"log/sheaf.log"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sheaf version")
  end
end
RUBY
